def make_input_table(excel_file, pasted_posts):
    if excel_file is not None:
        df = pd.read_excel(excel_file)

        if "Post text" not in df.columns:
            raise gr.Error("The Excel file must contain a column named: Post text")

        if "Post ID" not in df.columns:
            df["Post ID"] = [
                f"UPLOAD-{i:03d}" for i in range(1, len(df) + 1)
            ]

        return df[["Post ID", "Post text"]].dropna(subset=["Post text"])

    blocks = [
        block.strip()
        for block in pasted_posts.split("\n\n")
        if block.strip()
    ]

    if not blocks:
        raise gr.Error("Upload an Excel file or paste at least one post.")

    return pd.DataFrame({
        "Post ID": [f"PASTE-{i:03d}" for i in range(1, len(blocks) + 1)],
        "Post text": blocks
    })

